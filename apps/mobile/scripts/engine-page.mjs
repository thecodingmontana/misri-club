// Builds the Stockfish page the app runs offline: the website's engine (JS and
// wasm, apps/web/public/stockfish) inlined into one HTML string, so Play and
// Analyse need no connection. Runs on install; the output isn't committed.
import { readFileSync, writeFileSync } from 'node:fs'

const dir = new URL('../../web/public/stockfish/', import.meta.url)
const js = readFileSync(new URL('stockfish-19-lite-single.js', dir), 'utf8')
const wasm = readFileSync(new URL('stockfish-19-lite-single.wasm', dir))
// safe inside a <script>: no "</script>" can end it early
const inline = (value) => JSON.stringify(value).replace(/<\//g, '<\\/')

const page = `<!doctype html><meta charset="utf-8"><script>
const wasm = Uint8Array.from(atob(${inline(wasm.toString('base64'))}), (c) => c.charCodeAt(0))
const url = (parts, type) => URL.createObjectURL(new Blob(parts, { type }))
// the engine reads where its wasm is from its own address's #fragment
const engine = new Worker(url([${inline(js)}], 'text/javascript') + '#' + encodeURIComponent(url([wasm], 'application/wasm')))
const send = (line) => window.ReactNativeWebView.postMessage(line)
engine.onmessage = (event) => send(String(event.data))
engine.onerror = (event) => send('error The chess engine failed to start' + (event.message ? ': ' + event.message : '.'))
window.uci = (command) => engine.postMessage(command)
send('loaded')
</script>`

writeFileSync(
  new URL('../src/engine-page.generated.ts', import.meta.url),
  `// Generated by scripts/engine-page.mjs from apps/web/public/stockfish. Don't edit.\nexport const ENGINE_PAGE = ${JSON.stringify(page)}\n`,
)
