// Generates src/icons.generated.ts from the website's icon list
// (apps/web/src/components/icons.ts): the same Iconify glyphs (Solar,
// Hugeicons) under the same names, as SVG for react-native-svg.
// Run after changing that list: pnpm --filter @misri/mobile icons
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { getIconData, iconToSVG } from '@iconify/utils'

const require = createRequire(import.meta.url)
const list = readFileSync(
  new URL('../../web/src/components/icons.ts', import.meta.url),
  'utf8',
)
const sets = {}
const icons = {}
for (const [, name, set, icon] of list.matchAll(
  /export \{ default as (\w+) \} from '~icons\/([\w-]+)\/([\w-]+)'/g,
)) {
  sets[set] ??= require(`@iconify-json/${set}/icons.json`)
  const data = getIconData(sets[set], icon)
  if (!data) throw new Error(`No icon ${set}:${icon}`)
  const svg = iconToSVG(data)
  icons[name] = { body: svg.body, viewBox: svg.attributes.viewBox }
}

writeFileSync(
  new URL('../src/icons.generated.ts', import.meta.url),
  `// Generated by scripts/icons.mjs from apps/web/src/components/icons.ts. Don't edit.\n` +
    `export const ICONS = ${JSON.stringify(icons, null, 2)} as const\n\n` +
    'export type IconName = keyof typeof ICONS\n',
)
console.log(`${Object.keys(icons).length} icons`)
